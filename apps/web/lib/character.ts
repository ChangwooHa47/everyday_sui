/**
 * [Anthropic 전환용 보관] system 프롬프트 블록 배열 생성.
 * [0] 베이스 룰 + 프로필 → cache_control (대화 내내 불변)
 * [1] 메모리 → 캐시 breakpoint 뒤 (요약 갱신 시 바뀌어도 [0] 캐시는 유지)
 */
export function buildSystemBlocks(profile: CharacterProfile, memory: string) {
  return [
    {
      type: "text" as const,
      text: `${BASE_RULES}\n\n${buildProfileMd(profile)}`,
      cache_control: { type: "ephemeral" as const },
    },
    {
      type: "text" as const,
      text: `## 기억 (사용자와의 지난 대화에서)\n\n${memory.trim() || "(아직 없음 — 첫 대화)"}`,
    },
  ];
}

